-- Semua perubahan dan pembacaan data penjualan melalui fungsi tervalidasi.
create or replace function wk_private.require_user(p_owner boolean default false)
returns uuid language plpgsql stable security definer set search_path = '' as $$
declare v_id uuid := auth.uid(); v_role text;
begin
  select role into v_role from public.profiles where id = v_id;
  if v_id is null or v_role is null then
    raise exception using errcode = '42501', message = 'Silakan masuk terlebih dahulu.';
  end if;
  if v_role not in ('Pemilik', 'Kasir') or (p_owner and v_role <> 'Pemilik') then
    raise exception using errcode = '42501', message = 'Fitur ini hanya untuk Pemilik.';
  end if;
  return v_id;
end;
$$;

create or replace function public.get_products(p_offset integer default 0)
returns setof jsonb language plpgsql stable security definer set search_path = '' as $$
declare v_owner boolean;
begin
  perform wk_private.require_user();
  select role = 'Pemilik' into v_owner from public.profiles where id = auth.uid();
  return query select to_jsonb(p) || jsonb_build_object(
    'cost_price', case when v_owner then p.cost_price else 0 end)
  from public.products p order by p.name, p.id limit 200 offset greatest(p_offset, 0);
end;
$$;

create or replace function wk_private.validate_product(p_name text, p_cost integer,
  p_price integer, p_unit text)
returns void language plpgsql as $$
begin
  if p_name is null or length(btrim(p_name)) not between 1 and 100
    or p_unit is null or length(btrim(p_unit)) not between 1 and 20
    or p_cost is null or p_cost < 0 or p_price is null or p_price < 0 then
    raise exception using errcode = 'P0001', message = 'Nama, satuan, atau harga produk tidak valid.';
  end if;
end;
$$;

create or replace function public.create_product(p_name text, p_cost integer,
  p_price integer, p_stock integer, p_unit text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_product public.products%rowtype;
begin
  perform wk_private.require_user(true);
  perform wk_private.validate_product(p_name, p_cost, p_price, p_unit);
  if p_stock is null or p_stock < 0 then
    raise exception using errcode = 'P0001', message = 'Stok awal tidak valid.';
  end if;
  insert into public.products(name, cost_price, selling_price, stock, unit)
  values (btrim(p_name), p_cost, p_price, p_stock, btrim(p_unit)) returning * into v_product;
  return to_jsonb(v_product);
end;
$$;

create or replace function public.update_product(p_id bigint, p_name text,
  p_cost integer, p_price integer, p_unit text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_product public.products%rowtype;
begin
  perform wk_private.require_user(true);
  perform wk_private.validate_product(p_name, p_cost, p_price, p_unit);
  -- Stok tidak ditimpa dari form edit agar penjualan bersamaan tidak hilang.
  update public.products set name = btrim(p_name), cost_price = p_cost,
    selling_price = p_price, unit = btrim(p_unit)
  where id = p_id returning * into v_product;
  if not found then raise exception using errcode = 'P0001', message = 'Produk sudah dihapus.'; end if;
  return to_jsonb(v_product);
end;
$$;

-- Mengganti fungsi demo lama yang mengembalikan row, tanpa menghapus produk.
drop function if exists public.add_product_stock(bigint, integer);
create function public.add_product_stock(p_product_id bigint, p_quantity integer)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_product public.products%rowtype;
begin
  perform wk_private.require_user(true);
  if p_quantity is null or p_quantity <= 0 then
    raise exception using errcode = 'P0001', message = 'Jumlah stok harus lebih dari 0.';
  end if;
  update public.products set stock = stock + p_quantity where id = p_product_id
  returning * into v_product;
  if not found then raise exception using errcode = 'P0001', message = 'Produk sudah dihapus.'; end if;
  return to_jsonb(v_product);
end;
$$;

