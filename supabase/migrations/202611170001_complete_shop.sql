create schema if not exists wk_private;
revoke all on schema wk_private from public, anon, authenticated;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete restrict,
  full_name text not null check (length(btrim(full_name)) between 1 and 100),
  role text not null default 'Kasir' check (role in ('Pemilik', 'Kasir')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name varchar(100) not null check (btrim(name) <> ''),
  cost_price integer not null check (cost_price >= 0),
  selling_price integer not null check (selling_price >= 0),
  stock integer not null check (stock >= 0),
  unit varchar(20) not null check (btrim(unit) <> ''),
  created_at timestamptz not null default now()
);

create table if not exists public.transactions (
  id uuid primary key default gen_random_uuid(),
  invoice_code varchar(20) not null unique,
  created_by uuid not null references public.profiles(id) on delete restrict,
  total_price integer not null check (total_price >= 0),
  total_profit integer not null,
  cash_paid integer not null check (cash_paid >= total_price),
  change_paid integer not null check (change_paid = cash_paid - total_price),
  created_at timestamptz not null default now()
);

create table if not exists public.transaction_items (
  id bigint generated by default as identity primary key,
  transaction_id uuid not null references public.transactions(id) on delete restrict,
  product_id bigint references public.products(id) on delete set null,
  product_name varchar(100) not null,
  cost_price integer not null check (cost_price >= 0),
  selling_price integer not null check (selling_price >= 0),
  qty integer not null check (qty > 0),
  subtotal integer not null check (subtotal = selling_price::bigint * qty),
  profit integer not null check (profit = (selling_price::bigint - cost_price) * qty)
);
create index if not exists transactions_created_at_idx on public.transactions(created_at desc, id);
create index if not exists transactions_created_by_idx on public.transactions(created_by);
create index if not exists transaction_items_transaction_id_idx on public.transaction_items(transaction_id);
create index if not exists transaction_items_product_id_idx on public.transaction_items(product_id);
create sequence if not exists wk_private.invoice_number maxvalue 9999999999;

-- Metadata pengguna tidak dipercaya untuk menentukan peran.
create or replace function wk_private.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id, full_name, role)
  values (new.id, left(coalesce(nullif(btrim(new.raw_user_meta_data->>'full_name'), ''),
    nullif(split_part(new.email, '@', 1), ''), 'Pegawai'), 100), 'Kasir');
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute function wk_private.handle_new_user();

insert into public.profiles(id, full_name, role)
select id, left(coalesce(nullif(btrim(raw_user_meta_data->>'full_name'), ''),
  nullif(split_part(email, '@', 1), ''), 'Pegawai'), 100), 'Kasir'
from auth.users on conflict (id) do nothing;

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.transactions enable row level security;
alter table public.transaction_items enable row level security;

