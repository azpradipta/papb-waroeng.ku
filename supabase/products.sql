create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name varchar(100) not null check (btrim(name) <> ''),
  cost_price integer not null check (cost_price >= 0),
  selling_price integer not null check (selling_price >= 0),
  stock integer not null check (stock >= 0),
  unit varchar(20) not null check (btrim(unit) <> ''),
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;

-- Login aplikasi masih hard-coded, sehingga request Supabase saat ini memakai
-- role anon. Policy demo ini sengaja membuka CRUD products agar modul produk
-- bisa didemokan. Setelah Supabase Auth dibuat, hapus akses anon untuk operasi
-- tulis dan batasi INSERT/UPDATE/DELETE hanya untuk role Pemilik.
drop policy if exists "products_select_demo" on public.products;
create policy "products_select_demo"
on public.products for select
to anon, authenticated
using (true);

drop policy if exists "products_insert_demo" on public.products;
create policy "products_insert_demo"
on public.products for insert
to anon, authenticated
with check (true);

drop policy if exists "products_update_demo" on public.products;
create policy "products_update_demo"
on public.products for update
to anon, authenticated
using (true)
with check (true);

drop policy if exists "products_delete_demo" on public.products;
create policy "products_delete_demo"
on public.products for delete
to anon, authenticated
using (true);

grant select, insert, update, delete on table public.products
to anon, authenticated;
grant usage, select on sequence public.products_id_seq
to anon, authenticated;

-- Menambah stok langsung di database agar tidak memakai nilai stok lama dari
-- Flutter. Fungsi mengembalikan baris products yang sudah diperbarui.
create or replace function public.add_product_stock(
  p_product_id bigint,
  p_quantity integer
)
returns public.products
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_product public.products%rowtype;
begin
  if p_quantity <= 0 then
    raise exception using
      errcode = 'P0001',
      message = 'Jumlah stok harus lebih dari 0.';
  end if;

  update public.products as product
  set stock = product.stock + p_quantity
  where product.id = p_product_id
  returning product.* into v_product;

  if not found then
    raise exception using
      errcode = 'P0001',
      message = 'Produk tidak ditemukan.';
  end if;

  return v_product;
end;
$$;

revoke all on function public.add_product_stock(bigint, integer) from public;
grant execute on function public.add_product_stock(bigint, integer)
to anon, authenticated;

-- Mengurangi stok seluruh isi keranjang dalam satu transaksi database.
-- Jika satu produk tidak ditemukan atau stoknya kurang, seluruh perubahan
-- dibatalkan otomatis oleh PostgreSQL.
create or replace function public.decrease_product_stocks(p_items jsonb)
returns setof public.products
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_item jsonb;
  v_product_id bigint;
  v_quantity integer;
  v_product public.products%rowtype;
begin
  if p_items is null
      or jsonb_typeof(p_items) <> 'array'
      or jsonb_array_length(p_items) = 0 then
    raise exception using
      errcode = 'P0001',
      message = 'Keranjang masih kosong.';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_product_id := (v_item ->> 'product_id')::bigint;
    v_quantity := (v_item ->> 'quantity')::integer;

    if v_quantity <= 0 then
      raise exception using
        errcode = 'P0001',
        message = 'Jumlah penjualan harus lebih dari 0.';
    end if;

    update public.products as product
    set stock = product.stock - v_quantity
    where product.id = v_product_id
      and product.stock >= v_quantity
    returning product.* into v_product;

    if not found then
      raise exception using
        errcode = 'P0001',
        message = 'Produk tidak ditemukan atau stok tidak mencukupi.';
    end if;

    return next v_product;
  end loop;

  return;
end;
$$;

revoke all on function public.decrease_product_stocks(jsonb) from public;
grant execute on function public.decrease_product_stocks(jsonb)
to anon, authenticated;

